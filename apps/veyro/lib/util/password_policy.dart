//! Единая политика пароля кошелька (решение владельца: минимум 8 символов).
//! Один источник правды для создания И импорта — слабый пароль на импортном
//! пути равен слабому шифрованию vault-файла (Argon2id не спасает от
//! од символьных ключей).

/// Минимальная длина пароля кошелька.
const int kMinPasswordLength = 8;

/// Политике соответствуют непустые пароли длиной от [kMinPasswordLength].
bool isValidWalletPassword(String password) =>
    password.length >= kMinPasswordLength;
